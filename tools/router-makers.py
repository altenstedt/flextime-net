# Generates Flextime.Daemon/RouterMakers.Data.cs from the IEEE MA-L
# register.  Run from the repository root with the register downloaded
# from https://standards-oui.ieee.org/oui/oui.csv:
#
#   python3 -I tools/router-makers.py oui.csv > Flextime.Daemon/RouterMakers.Data.cs
#
# Only makers that say something about where a router is are kept:
# phone makers, travel routers, virtual machines and the usual office
# and home network equipment.  Everything else reads as Unknown.

import base64
import csv
import re
import sys

# Name, kind, pattern over the organization name.  The first match wins.
MAKERS = [
    ("Apple", "Phone", r"^Apple, Inc"),
    ("Samsung", "Phone", r"^Samsung Electronics"),
    ("Google", "Phone", r"^Google"),
    ("Xiaomi", "Phone", r"Xiaomi"),
    ("OnePlus", "Phone", r"OnePlus"),
    ("Motorola", "Phone", r"^Motorola Mobility"),
    ("Sony", "Phone", r"^Sony Mobile|^Sony Corporation"),
    ("Nokia (HMD)", "Phone", r"^HMD Global"),
    ("GL.iNet", "Travel", r"^GL Technologies"),
    ("VMware", "Virtual", r"^VMware"),
    ("Parallels", "Virtual", r"^Parallels"),
    ("VirtualBox", "Virtual", r"^PCS Systemtechnik"),
    ("Ubiquiti", "Network", r"^Ubiquiti"),
    ("Cisco", "Network", r"^Cisco"),
    ("HPE Aruba", "Network", r"^Aruba|^Hewlett Packard Enterprise"),
    ("AVM (Fritz!Box)", "Network", r"^AVM "),
    ("TP-Link", "Network", r"TP-LINK|TP-Link"),
    ("Netgear", "Network", r"^NETGEAR|^Netgear"),
    ("ASUS", "Network", r"^ASUSTek"),
    ("Zyxel", "Network", r"^Zyxel|^ZyXEL"),
    ("Juniper", "Network", r"^Juniper Networks"),
    ("Fortinet", "Network", r"^Fortinet"),
    # Huawei registers its consumer arm apart: phones and mobile Wi-Fi.
    ("Huawei", "Phone", r"^Huawei Device"),
    ("Huawei", "Network", r"^Huawei|^HUAWEI"),
    ("ZTE", "Network", r"^zte corporation"),
    ("Sagemcom", "Network", r"^Sagemcom"),
    ("Technicolor", "Network", r"^Technicolor"),
    ("Arris", "Network", r"^ARRIS|^Arris"),
    ("Linksys", "Network", r"^Linksys|^Belkin"),
    ("D-Link", "Network", r"^D-Link|^D-LINK"),
    ("eero", "Network", r"^eero"),
    ("Extreme Networks", "Network", r"^Extreme Networks"),
    ("Ruckus", "Network", r"^Ruckus"),
    ("MikroTik", "Network", r"^Routerboard\.com|^Mikrotik|^MikroTik"),
    ("Sophos", "Network", r"^Sophos"),
    ("Palo Alto Networks", "Network", r"^Palo Alto Networks"),
    ("Microsoft", "Network", r"^Microsoft"),
]

# Prefixes the register does not name usefully.  QEMU's is locally
# administered, so it is not in the register at all.
EXTRA = {
    "525400": "QEMU",
    "00155D": "Hyper-V",
}
EXTRA_KINDS = {"QEMU": "Virtual", "Hyper-V": "Virtual"}

names = [name for name, _, _ in MAKERS] + list(EXTRA_KINDS)
kinds = [kind for _, kind, _ in MAKERS] + list(EXTRA_KINDS.values())
patterns = [re.compile(pattern) for _, _, pattern in MAKERS]

entries = {}

with open(sys.argv[1], encoding="utf-8") as file:
    for row in csv.reader(file):
        if row[0] != "MA-L":
            continue

        for index, pattern in enumerate(patterns):
            if pattern.search(row[2]):
                entries[row[1].upper()] = index
                break

for prefix, name in EXTRA.items():
    entries[prefix] = names.index(name)

packed = bytearray()

for prefix in sorted(entries):
    packed += bytes.fromhex(prefix) + bytes([entries[prefix]])

encoded = base64.b64encode(packed).decode()
lines = [encoded[i:i + 76] for i in range(0, len(encoded), 76)]

print("// <auto-generated>")
print("// Generated by tools/router-makers.py from the IEEE MA-L register.")
print("// </auto-generated>")
print()
print("namespace Flextime.Daemon;")
print()
print("public static partial class RouterMakers")
print("{")
print("    private static readonly (string Name, MakerKind Kind)[] Makers =")
print("    [")
for name, kind in zip(names, kinds):
    print(f'        ("{name}", MakerKind.{kind}),')
print("    ];")
print()
print(f"    // {len(entries)} prefixes, each three bytes of prefix and one of maker index, sorted.")
print("    private const string Packed =")
for i, line in enumerate(lines):
    end = ";" if i == len(lines) - 1 else " +"
    print(f'        "{line}"{end}')
print("}")
